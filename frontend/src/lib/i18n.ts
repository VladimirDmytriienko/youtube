export function getStatusConfig(lang: AppLang, status: VideoStatus) {
  const tr = I18N[lang] || I18N.uk;
  switch (status) {
    case 'planning':
      return {
        label: tr.status.planning,
        badgeClass: 'bg-zinc-500/15 text-zinc-400 border-zinc-500/30 dark:bg-zinc-500/10 dark:text-zinc-400',
      };
    case 'scheduled':
      return {
        label: tr.status.scheduled,
        badgeClass: 'bg-amber-500/15 text-amber-600 border-amber-500/30 dark:bg-amber-500/10 dark:text-amber-500',
      };
    case 'posted':
      return {
        label: tr.status.posted,
        badgeClass: 'bg-emerald-500/15 text-emerald-600 border-emerald-500/30 dark:bg-emerald-500/10 dark:text-emerald-500',
      };
    default:
      return {
        label: status,
        badgeClass: 'bg-secondary text-foreground',
      };
  }
}
